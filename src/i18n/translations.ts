const DICTIONARIES: Record<LanguageCode, Record<TranslationKey, string>> = {
  en,
  es,
  hi,
  fr,
  pt,
};

export function t(lang: LanguageCode, key: TranslationKey): string {
  return DICTIONARIES[lang]?.[key] ?? en[key] ?? key;
}

export function cropLabel(lang: LanguageCode, cropId: string): string {
  const key = `crop_${cropId}` as TranslationKey;
  const dictVal = DICTIONARIES[lang]?.[key] ?? en[key];
  if (dictVal && dictVal !== key) return dictVal;
  return ECOCROP_BY_ID[cropId]?.CommonName ?? cropId;
}

export function equipmentLabel(lang: LanguageCode, eqId: EquipmentId): string {
  const key = `eq_${eqId}` as TranslationKey;
  return DICTIONARIES[lang]?.[key] ?? en[key] ?? eqId;
}

export function monthLabel(lang: LanguageCode, monthIndex: number): string {
  const key = `month_${monthIndex}` as TranslationKey;
  return DICTIONARIES[lang]?.[key] ?? en[key] ?? String(monthIndex + 1);
}
