export function inferTraditionalRegionalCrops(loc: LocationOption): string[] {
  if (loc.traditionalCrops?.length) return loc.traditionalCrops;

  const matchedHub = GLOBAL_FARM_HUBS.find(
    (h) =>
      h.id === loc.id ||
      (Math.abs(h.lat - loc.lat) < 2.5 && Math.abs(h.lon - loc.lon) < 2.5)
  );
  if (matchedHub?.traditionalCrops) return matchedHub.traditionalCrops;

  const absLat = Math.abs(loc.lat);
  if (absLat < 22) {
    return ['rice', 'corn', 'soybeans', 'chickpeas', 'sorghum'];
  }
  if (absLat < 36) {
    return ['winter_wheat', 'cotton', 'corn', 'chickpeas', 'sorghum', 'soybeans'];
  }
  if (absLat < 47) {
    return ['corn', 'soybeans', 'winter_wheat', 'sunflower', 'alfalfa'];
  }
  return ['winter_wheat', 'barley', 'canola', 'potatoes'];
}

export function makeLocationKey(lat: number, lon: number): string {
  return `${lat.toFixed(3)},${lon.toFixed(3)}`;
}
